#!/usr/bin/env bash
set -euo pipefail

# lock-requirements.sh: compile server/requirements.{linux,macos}.txt from server/requirements.in

here="$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)"

REQ_IN="$here/server/requirements.in"
REQ_LINUX="$here/server/requirements.linux.txt"
REQ_MACOS="$here/server/requirements.macos.txt"

usage() {
  echo "Usage: $0 [--check]" >&2
  exit 2
}

CHECK_ONLY=0
if [ "$#" -eq 1 ]; then
  if [ "$1" = "--check" ]; then
    CHECK_ONLY=1
  else
    usage
  fi
elif [ "$#" -gt 1 ]; then
  usage
fi

if ! command -v uv >/dev/null 2>&1; then
  echo "Error: 'uv' is required but not found in PATH" >&2
  exit 1
fi

if [ ! -f "$REQ_IN" ]; then
  echo "Error: Requirements file not found: $REQ_IN" >&2
  exit 1
fi

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT INT TERM

compile_locks() {
  local out_linux="$1"
  local out_macos="$2"
  local work_dir="$3"

  local raw_linux="$work_dir/linux.raw"
  local raw_macos="$work_dir/macos.raw"
  local constraints="$work_dir/constraints.txt"

  # Compile Linux lock file
  uv pip compile "$REQ_IN" \
    --python-version 3.12 \
    --python-platform x86_64-unknown-linux-gnu \
    --generate-hashes \
    --no-header \
    -o "$raw_linux"

  # Extract pinned versions to use as constraints for macOS
  grep -E '^[a-zA-Z0-9_.-]+==' "$raw_linux" | sed -E 's/[[:space:]]*\\$//' > "$constraints"

  # Compile macOS lock file constrained by Linux versions
  MACOSX_DEPLOYMENT_TARGET=14.0 uv pip compile "$REQ_IN" \
    -c "$constraints" \
    --python-version 3.12 \
    --python-platform aarch64-apple-darwin \
    --generate-hashes \
    --no-header \
    -o "$raw_macos"

  # Write stable header and assemble Linux lock file
  printf '# generated by scripts/lock-requirements.sh; do not edit\n' > "$out_linux"
  cat "$raw_linux" >> "$out_linux"

  # Write stable header and assemble macOS lock file (stripping transient constraints path comment)
  printf '# generated by scripts/lock-requirements.sh; do not edit\n' > "$out_macos"
  sed -E '/^[[:space:]]*#[[:space:]]+-c[[:space:]]+/d' "$raw_macos" >> "$out_macos"
}

TMP_LINUX="$TMP_DIR/requirements.linux.txt"
TMP_MACOS="$TMP_DIR/requirements.macos.txt"

compile_locks "$TMP_LINUX" "$TMP_MACOS" "$TMP_DIR"

# Verify that Linux and macOS pin sets agree
grep -E '^[a-zA-Z0-9_.-]+==' "$TMP_LINUX" | sed -E 's/[[:space:]]*\\$//' | sort > "$TMP_DIR/pins_linux.txt"
grep -E '^[a-zA-Z0-9_.-]+==' "$TMP_MACOS" | sed -E 's/[[:space:]]*\\$//' | sort > "$TMP_DIR/pins_macos.txt"

if ! cmp -s "$TMP_DIR/pins_linux.txt" "$TMP_DIR/pins_macos.txt"; then
  echo "Error: Linux and macOS pins differ:" >&2
  diff -u "$TMP_DIR/pins_linux.txt" "$TMP_DIR/pins_macos.txt" >&2 || true
  exit 1
fi

if [ "$CHECK_ONLY" -eq 1 ]; then
  if [ ! -f "$REQ_LINUX" ]; then
    echo "Error: $REQ_LINUX does not exist" >&2
    echo "Run 'scripts/lock-requirements.sh' to update lock files" >&2
    exit 1
  fi

  if [ ! -f "$REQ_MACOS" ]; then
    echo "Error: $REQ_MACOS does not exist" >&2
    echo "Run 'scripts/lock-requirements.sh' to update lock files" >&2
    exit 1
  fi

  has_diff=0
  if ! cmp -s "$TMP_LINUX" "$REQ_LINUX"; then
    echo "Error: $REQ_LINUX is out of date" >&2
    diff -u "$REQ_LINUX" "$TMP_LINUX" >&2 || true
    has_diff=1
  fi

  if ! cmp -s "$TMP_MACOS" "$REQ_MACOS"; then
    echo "Error: $REQ_MACOS is out of date" >&2
    diff -u "$REQ_MACOS" "$TMP_MACOS" >&2 || true
    has_diff=1
  fi

  if [ "$has_diff" -ne 0 ]; then
    echo "Run 'scripts/lock-requirements.sh' to update lock files" >&2
    exit 1
  fi

  echo "Server lock files match requirements.in and agree across platforms."
else
  mv "$TMP_LINUX" "$REQ_LINUX"
  mv "$TMP_MACOS" "$REQ_MACOS"
  echo "Updated $REQ_LINUX and $REQ_MACOS."
fi
