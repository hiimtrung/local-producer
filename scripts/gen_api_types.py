"""Generate web/src/api/types.gen.ts from the server's OpenAPI schema (the pydantic models in server/app).

The web UI imports every API type from that file, so changing a model on the server and running `make api-types`
turns every place in the UI that no longer fits into a TypeScript error. `--check` fails when the file is stale
(run by the tests and CI). Covers the JSON Schema subset pydantic emits: objects, $ref, anyOf/oneOf, enum/const,
arrays, maps, primitives; an empty schema is JsonValue.

  python scripts/gen_api_types.py [--check]
"""

import argparse
import json
import os
import re
import sys
from typing import Any

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "web", "src", "api", "types.gen.ts")
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")

Schema = dict[str, Any]

HEADER = """\
// Generated by scripts/gen_api_types.py from the server's OpenAPI schema (server/app, pydantic). Do not edit:
// change the server model and run `make api-types`.

export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };
"""


def type_name(component: str) -> str:
    """FastAPI names a model used for both requests and responses "X-Input" / "X-Output"."""
    if component.endswith("-Output"):
        return component[: -len("-Output")]
    if component.endswith("-Input"):
        return component[: -len("-Input")] + "Input"
    return re.sub(r"[^A-Za-z0-9_]", "_", component)


def literal(v: Any) -> str:
    return json.dumps(v)


def ts_type(s: Schema, indent: str = "") -> str:
    if not s:
        return "JsonValue"
    if "$ref" in s:
        return type_name(s["$ref"].rsplit("/", 1)[1])
    if "const" in s:
        return literal(s["const"])
    if "enum" in s:
        return " | ".join(literal(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = [ts_type(x, indent) for x in s[key]]
            return " | ".join(dict.fromkeys(parts))
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}, indent) for x in t)
    if t == "string":
        return "Blob" if s.get("format") == "binary" else "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        item = ts_type(s.get("items", {}), indent)
        return f"({item})[]" if " " in item else f"{item}[]"
    if t == "object" or "properties" in s:
        if s.get("properties"):
            return object_body(s, indent)
        extra = s.get("additionalProperties", {})
        return f"{{ [key: string]: {ts_type(extra if isinstance(extra, dict) else {}, indent)} }}"
    return "unknown"


def doc(s: Schema, indent: str) -> str:
    text = s.get("description") or ""
    if "default" in s and s["default"] is not None and not isinstance(s["default"], dict | list):
        text = f"{text} (default {literal(s['default'])})".strip()
    if not text:
        return ""
    return f"{indent}/** {text.replace('*/', '* /')} */\n"


def object_body(s: Schema, indent: str) -> str:
    required = set(s.get("required", []))
    inner = indent + "  "
    lines = ["{"]
    for name, prop in s["properties"].items():
        key = name if IDENT.match(name) else json.dumps(name)
        opt = "" if name in required else "?"
        lines.append(f"{doc(prop, inner)}{inner}{key}{opt}: {ts_type(prop, inner)};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def generate(openapi: Schema) -> str:
    out = [HEADER]
    for component, s in openapi["components"]["schemas"].items():
        name = type_name(component)
        if name == "JsonValue":  # pydantic's JsonValue: the header defines it
            continue
        text = " ".join((s.get("description") or "").split())
        comment = f"/** {text} */\n" if text else ""
        if s.get("type") == "object" and s.get("properties"):
            out.append(f"{comment}export interface {name} {object_body(s, '')}\n")
        else:
            out.append(f"{comment}export type {name} = {ts_type(s)};\n")
    return "\n".join(out)


def build() -> str:
    sys.path.insert(0, os.path.join(ROOT, "server"))
    from app.main import create_app

    return generate(create_app().openapi())


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="fail if the generated file is not up to date")
    args = p.parse_args()
    text = build()
    if args.check:
        try:
            with open(OUT) as f:
                current = f.read()
        except OSError:
            current = ""
        if current != text:
            print(f"{os.path.relpath(OUT, ROOT)} is stale: run `make api-types`", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
